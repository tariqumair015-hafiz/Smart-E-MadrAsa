import fs from 'fs';
import path from 'path';

const rootDir = 'node_modules';
let corruptedFiles = [];
let zeroByteFiles = [];
let scannedCount = 0;

function scanDir(dir) {
  let files;
  try {
    files = fs.readdirSync(dir);
  } catch (e) {
    return;
  }

  for (const file of files) {
    const fullPath = path.join(dir, file);
    let stat;
    try {
      stat = fs.lstatSync(fullPath);
    } catch (e) {
      continue;
    }

    if (stat.isDirectory()) {
      scanDir(fullPath);
    } else if (stat.isFile()) {
      const ext = path.extname(fullPath).toLowerCase();
      if (ext === '.js' || ext === '.json' || ext === '.jsx' || ext === '.ts' || ext === '.tsx' || ext === '.css') {
        scannedCount++;
        if (stat.size === 0) {
          zeroByteFiles.push(fullPath);
        } else {
          // Check if file is filled with null bytes
          try {
            // We can read first 1024 bytes
            const fd = fs.openSync(fullPath, 'r');
            const buffer = Buffer.alloc(Math.min(stat.size, 1024));
            fs.readSync(fd, buffer, 0, buffer.length, 0);
            fs.closeSync(fd);

            // If it's all null bytes, it's corrupted
            let allNull = true;
            for (let i = 0; i < buffer.length; i++) {
              if (buffer[i] !== 0) {
                allNull = false;
                break;
              }
            }
            if (allNull && stat.size > 0) {
              corruptedFiles.push(fullPath);
            }
          } catch (err) {
            // Ignore read errors
          }
        }
      }
    }
  }
}

console.log('Scanning node_modules for corrupted or 0-byte files...');
scanDir(rootDir);
console.log(`Scanned ${scannedCount} files.`);
console.log('\n--- Zero Byte Files ---');
console.log(zeroByteFiles.length ? zeroByteFiles.join('\n') : 'None');
console.log('\n--- Null Byte Corrupted Files ---');
console.log(corruptedFiles.length ? corruptedFiles.join('\n') : 'None');
